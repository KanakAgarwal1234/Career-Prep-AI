async function http(method, url, { token, form, json, auth = "Bearer" } = {}) {
  const headers = { authorization: `${auth} ${token}` };
  let body;
  if (form) {
    headers["content-type"] = "application/x-www-form-urlencoded";
    body = new URLSearchParams(form).toString();
  } else if (json !== undefined) {
    headers["content-type"] = "application/json";
    body = JSON.stringify(json);
  }
  const res = await fetch(url, { method, headers, body });
  const text = await res.text();
  let data = null;
  try {
    data = text ? JSON.parse(text) : null;
  } catch {
    data = { raw: text };
  }
  if (!res.ok) {
    const msg = data?.error?.message || data?.message || data?.error || text || res.statusText;
    const err = new Error(`${res.status} ${typeof msg === "string" ? msg : JSON.stringify(msg)}`);
    err.status = res.status;
    throw err;
  }
  return data;
}

function run(cmd, args, opts = {}) {
  const r = spawnSync(cmd, args, { stdio: "inherit", shell: process.platform === "win32", ...opts });
  return r.status === 0;
}

function gitRepoSlug() {
  const r = spawnSync("git", ["remote", "get-url", "origin"], { cwd: REPO_DIR, encoding: "utf8" });
  const m = (r.stdout || "").trim().match(/github\.com[:/]([^/]+\/[^/.]+?)(?:\.git)?$/i);
  return m ? m[1] : null;
}

/** Percent-encodes the password inside a Postgres URL (Supabase passwords often contain @ # / ?). */
function encodeDbUrl(raw) {
  const m = raw.match(/^(postgres(?:ql)?:\/\/)([^:/@]+):(.*)@([^@]+)$/);
  if (!m) return raw;
  const [, scheme, user, password, rest] = m;
  const encoded = /%[0-9A-Fa-f]{2}/.test(password) ? password : encodeURIComponent(password);
  return `${scheme}${user}:${encoded}@${rest}`;
}

