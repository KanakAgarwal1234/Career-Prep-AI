#!/usr/bin/env node
/**
 * CareerPrep AI — one-time setup. Run on your own machine from careerprep-ai/:
 *
 *   npm run setup
 *
 * Asks for each key one at a time (secrets are hidden as you type), then:
 *   1. writes careerprep-ai/.env.local
 *   2. pushes the database schema to Supabase (supabase db push)
 *   3. creates/updates the Vercel project with Root Directory = careerprep-ai,
 *      uploads the env vars and deploys
 *   4. creates the Stripe Pro price + webhook and points Supabase Auth at
 *      the production URL
 *
 * Safe to re-run: press Enter to keep any value already in .env.local.
 * Nothing secret is printed, committed or sent anywhere except the service it belongs to.
 */
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { createInterface } from "node:readline";
import { fileURLToPath } from "node:url";

const APP_DIR = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const REPO_DIR = resolve(APP_DIR, "..");
const ENV_PATH = join(APP_DIR, ".env.local");
const ROOT_DIRECTORY = "careerprep-ai";
const SUPABASE_CLI = "supabase@2.121.0";
const WEBHOOK_EVENTS = ["checkout.session.completed", "customer.subscription.updated", "customer.subscription.deleted"];

// Overridable only so the script can be exercised against local mocks.
const STRIPE_API = process.env.CP_STRIPE_API || "https://api.stripe.com/v1";
const VERCEL_API = process.env.CP_VERCEL_API || "https://api.vercel.com";
const SUPABASE_API = process.env.CP_SUPABASE_API || "https://api.supabase.com/v1";

/* ------------------------------------------------------------------ */
/* Terminal helpers                                                    */
/* ------------------------------------------------------------------ */

const tty = process.stdin.isTTY;
const c = (code) => (s) => (process.stdout.isTTY ? `\x1b[${code}m${s}\x1b[0m` : String(s));
const bold = c(1);
const dim = c(2);
const green = c(32);
const yellow = c(33);
const red = c(31);

const rl = createInterface({ input: process.stdin, output: process.stdout, terminal: tty, historySize: 0 });
let muted = false;
let query = "";
// Mask secrets: typed/pasted characters become •, line redraws keep the prompt visible.
rl._writeToOutput = function write(s) {
  if (!muted || s === "\r\n" || s === "\n") return rl.output.write(s);
  if (s.startsWith(query)) return rl.output.write(query + "•".repeat(s.length - query.length));
  rl.output.write("•".repeat(s.length));
};
const pending = [];
const waiters = [];
rl.on("line", (l) => (waiters.length ? waiters.shift()(l) : pending.push(l)));
rl.on("close", () => waiters.splice(0).forEach((w) => w("")));

function ask(question, { secret = false } = {}) {
  query = question;
  muted = secret && tty;
  rl.setPrompt(question);
  rl.prompt();
  return new Promise((done) => {
    const finish = (answer) => {
      muted = false;
      if (!tty) process.stdout.write(secret && answer ? "(hidden)\n" : `${answer}\n`);
      done(answer.trim());
    };
    pending.length ? finish(pending.shift()) : waiters.push(finish);
  });
}

async function confirm(question, def = true) {
  const a = (await ask(`${question} ${dim(def ? "[Y/n]" : "[y/N]")} `)).toLowerCase();
  return a ? a.startsWith("y") : def;
}

const mask = (v) => (!v ? "" : v.length <= 10 ? "•••" : `${v.slice(0, 6)}…${v.slice(-4)}`);
const step = (n, title) => console.log(`\n${bold(`[${n}/5] ${title}`)}`);
const ok = (msg) => console.log(`  ${green("✓")} ${msg}`);
const warn = (msg) => console.log(`  ${yellow("!")} ${msg}`);
const fail = (msg) => console.log(`  ${red("✗")} ${msg}`);

/* ------------------------------------------------------------------ */
/* .env.local                                                          */
/* ------------------------------------------------------------------ */

function readEnv() {
  if (!existsSync(ENV_PATH)) return {};
  const out = {};
  for (const line of readFileSync(ENV_PATH, "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (m) out[m[1]] = m[2].replace(/^(['"])(.*)\1$/, "$2");
  }
  return out;
}

const GROUPS = [
  ["Supabase", ["NEXT_PUBLIC_SUPABASE_URL", "NEXT_PUBLIC_SUPABASE_ANON_KEY", "SUPABASE_SERVICE_ROLE_KEY"]],
  ["Stripe", ["STRIPE_SECRET_KEY", "STRIPE_PRICE_ID", "STRIPE_WEBHOOK_SECRET", "STRIPE_MODE", "NEXT_PUBLIC_PRO_PRICE_LABEL", "NEXT_PUBLIC_PRO_INTERVAL_LABEL"]],
  ["AI & voice", ["OPENAI_API_KEY", "ANTHROPIC_API_KEY", "ELEVENLABS_API_KEY"]],
  ["Site", ["NEXT_PUBLIC_SITE_URL"]],
];

function writeEnv(env) {
  const known = new Set(GROUPS.flatMap(([, keys]) => keys));
  const quote = (v) => (/[\s#"']/.test(v) ? JSON.stringify(v) : v);
  let out = "# Generated by `npm run setup` — never commit this file.\n";
  for (const [title, keys] of GROUPS) {
    const present = keys.filter((k) => env[k]);
    if (!present.length) continue;
    out += `\n# ${title}\n${present.map((k) => `${k}=${quote(env[k])}`).join("\n")}\n`;
  }
  const extra = Object.keys(env).filter((k) => !known.has(k) && env[k]);
  if (extra.length) out += `\n# Other\n${extra.map((k) => `${k}=${quote(env[k])}`).join("\n")}\n`;
  writeFileSync(ENV_PATH, out, { mode: 0o600 });
}

async function askKey(env, key, { label, hint, secret = false, optional = false, check }) {
  const current = env[key];
  for (;;) {
    console.log(`\n  ${bold(label)}${optional ? dim(" (optional)") : ""}\n  ${dim(hint)}`);
    const keepNote = current ? dim(` [Enter = keep ${secret ? mask(current) : current}]`) : optional ? dim(" [Enter = skip]") : "";
    const v = await ask(`  ${key}${keepNote}: `, { secret });
    if (!v) {
      if (current || optional) return current || "";
      warn("Required — paste the value, or type skip to leave it empty for now.");
      continue;
    }
    if (v === "skip") return "";
    const problem = check?.(v);
    if (problem) {
      warn(problem);
      continue;
    }
    return v;
  }
}

