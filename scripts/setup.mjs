async function collectKeys(env) {
  step(1, "Keys → careerprep-ai/.env.local");
  console.log(dim("  Secrets are hidden as you type. Type skip to leave one empty."));

  env.NEXT_PUBLIC_SUPABASE_URL = (await askKey(env, "NEXT_PUBLIC_SUPABASE_URL", {
    label: "Supabase project URL",
    hint: "Supabase → Project Settings → Data API → Project URL (https://xxxx.supabase.co)",
    check: (v) => (/^https:\/\/[a-z0-9-]+\.supabase\.(co|in)\/?$/.test(v) ? null : "Expected https://<project-ref>.supabase.co"),
  })).replace(/\/$/, "");
  env.NEXT_PUBLIC_SUPABASE_ANON_KEY = await askKey(env, "NEXT_PUBLIC_SUPABASE_ANON_KEY", {
    label: "Supabase anon / publishable key",
    hint: "Project Settings → API Keys → anon (eyJ…) or publishable (sb_publishable_…) — safe for the browser",
    check: (v) => (/^(eyJ|sb_publishable_)/.test(v) ? null : "Expected a key starting with eyJ… or sb_publishable_…"),
  });
  env.SUPABASE_SERVICE_ROLE_KEY = await askKey(env, "SUPABASE_SERVICE_ROLE_KEY", {
    label: "Supabase service_role / secret key",
    hint: "Same page → service_role (eyJ…) or secret (sb_secret_…) — server only, this is what verifies Pro",
    secret: true,
    check: (v) => (/^(eyJ|sb_secret_)/.test(v) ? null : "Expected a key starting with eyJ… or sb_secret_…"),
  });

  env.STRIPE_SECRET_KEY = await askKey(env, "STRIPE_SECRET_KEY", {
    label: "Stripe secret key",
    hint: "Stripe → Developers → API keys. Use sk_test_… until you've tested a purchase end to end.",
    secret: true,
    check: (v) => (/^(sk|rk)_(test|live)_/.test(v) ? null : "Expected sk_test_…, sk_live_… or a restricted rk_… key"),
  });
  env.STRIPE_PRICE_ID = await askKey(env, "STRIPE_PRICE_ID", {
    label: "Stripe price ID for Pro",
    hint: "price_… from a recurring product. Leave empty and I'll create “CareerPrep Pro” for you.",
    optional: true,
    check: (v) => (v.startsWith("price_") ? null : "Expected price_…"),
  });
  if (!env.STRIPE_PRICE_ID && env.STRIPE_SECRET_KEY) await createStripePrice(env);
  else if (env.STRIPE_PRICE_ID && env.STRIPE_SECRET_KEY) await labelFromPrice(env);

  env.OPENAI_API_KEY = await askKey(env, "OPENAI_API_KEY", {
    label: "OpenAI API key",
    hint: "platform.openai.com → API keys. Enables AI rewrites + critique, HD voice and Whisper. Skip to stay offline.",
    secret: true,
    optional: true,
  });
  env.ANTHROPIC_API_KEY = await askKey(env, "ANTHROPIC_API_KEY", {
    label: "Anthropic API key",
    hint: "console.anthropic.com → API keys. Used for the AI engine when OpenAI is not set.",
    secret: true,
    optional: true,
  });
  env.ELEVENLABS_API_KEY = await askKey(env, "ELEVENLABS_API_KEY", {
    label: "ElevenLabs API key",
    hint: "elevenlabs.io → Profile → API keys. Most natural interviewer voice.",
    secret: true,
    optional: true,
  });

  writeEnv(env);
  ok(`Saved ${ENV_PATH.replace(REPO_DIR + "/", "")} (git-ignored)`);
}

async function createStripePrice(env) {
  if (!(await confirm("  Create the Pro subscription price in Stripe now?"))) return;
  const amount = Number((await ask(`  Monthly price ${dim("[19]")}: `)) || 19);
  const currency = ((await ask(`  Currency ${dim("[usd]")}: `)) || "usd").toLowerCase();
  try {
    const product = await http("POST", `${STRIPE_API}/products`, {
      token: env.STRIPE_SECRET_KEY,
      form: { name: "CareerPrep Pro", description: "Full adaptive AI mock interviews and delivery analytics" },
    });
    const zeroDecimal = ["jpy", "krw", "vnd", "clp", "isk", "ugx", "xof", "xaf"].includes(currency);
    const price = await http("POST", `${STRIPE_API}/prices`, {
      token: env.STRIPE_SECRET_KEY,
      form: {
        product: product.id,
        currency,
        unit_amount: String(Math.round(amount * (zeroDecimal ? 1 : 100))),
        "recurring[interval]": "month",
        nickname: "Pro monthly",
      },
    });
    env.STRIPE_PRICE_ID = price.id;
    env.NEXT_PUBLIC_PRO_PRICE_LABEL = new Intl.NumberFormat("en", { style: "currency", currency: currency.toUpperCase(), maximumFractionDigits: Number.isInteger(amount) ? 0 : 2 }).format(amount);
    env.NEXT_PUBLIC_PRO_INTERVAL_LABEL = "month";
    ok(`Created ${price.id} (${env.NEXT_PUBLIC_PRO_PRICE_LABEL}/month)`);
  } catch (err) {
    fail(`Stripe: ${err.message}`);
  }
}

/** Shows the real price on the pricing page instead of the $19 placeholder. */
async function labelFromPrice(env) {
  try {
    const price = await http("GET", `${STRIPE_API}/prices/${env.STRIPE_PRICE_ID}`, { token: env.STRIPE_SECRET_KEY });
    const zeroDecimal = ["jpy", "krw", "vnd", "clp", "isk", "ugx", "xof", "xaf"].includes(price.currency);
    const amount = price.unit_amount / (zeroDecimal ? 1 : 100);
    env.NEXT_PUBLIC_PRO_PRICE_LABEL = new Intl.NumberFormat("en", { style: "currency", currency: price.currency.toUpperCase(), maximumFractionDigits: Number.isInteger(amount) ? 0 : 2 }).format(amount);
    env.NEXT_PUBLIC_PRO_INTERVAL_LABEL = price.recurring?.interval || "one-time";
    env.STRIPE_MODE = price.recurring ? "" : "payment"; // one-time prices need a payment-mode checkout
    ok(`Price ${price.id}: ${env.NEXT_PUBLIC_PRO_PRICE_LABEL}/${env.NEXT_PUBLIC_PRO_INTERVAL_LABEL}`);
  } catch (err) {
    fail(`Stripe price lookup: ${err.message}`);
  }
}

async function pushSchema() {
  step(2, "Supabase database schema");
  console.log(dim("  Applies supabase/migrations/* (tables, row-level security, storage bucket). Safe to re-run."));
  if (!(await confirm("  Push the schema now?"))) return;
  console.log(dim("  Supabase → Connect (top bar) → Session pooler → copy the URI. Use the pooler, not “Direct” (IPv6-only)."));
  let url = await ask("  Database connection string: ", { secret: true });
  if (!url) return warn("Skipped — re-run setup when you have the connection string.");
  if (url.includes("[YOUR-PASSWORD]")) url = url.replace("[YOUR-PASSWORD]", await ask("  Database password: ", { secret: true }));
  const pushed = run("npx", ["-y", SUPABASE_CLI, "db", "push", "--db-url", encodeDbUrl(url), "--yes"], { cwd: APP_DIR });
  if (pushed) ok("Schema pushed");
  else fail("Push failed — check the password/connection string and run setup again (it skips what's already applied).");
}

async function vercelProject(env, state) {
  step(3, "Vercel project (Root Directory = careerprep-ai) + env vars + deploy");
  if (!(await confirm("  Set up Vercel from here?"))) return;
  console.log(dim("  vercel.com/account/tokens → Create token (scope: your account or team). Not saved anywhere."));
  const token = await ask("  Vercel token: ", { secret: true });
  if (!token) return warn("Skipped.");
  const team = await ask(`  Team slug ${dim("[Enter = personal account]")}: `);
  const name = (await ask(`  Project name ${dim("[careerprep-ai]")}: `)) || "careerprep-ai";
  const q = (path) => `${VERCEL_API}${path}${team ? `${path.includes("?") ? "&" : "?"}slug=${encodeURIComponent(team)}` : ""}`;

  let project;
  try {
    project = await http("GET", q(`/v9/projects/${encodeURIComponent(name)}`), { token });
    project = await http("PATCH", q(`/v9/projects/${project.id}`), { token, json: { rootDirectory: ROOT_DIRECTORY, framework: "nextjs" } });
    ok(`Updated project “${name}” → Root Directory ${ROOT_DIRECTORY}`);
  } catch (err) {
    if (err.status !== 404) return fail(`Vercel: ${err.message}`);
    const repo = gitRepoSlug();
    const base = { name, framework: "nextjs", rootDirectory: ROOT_DIRECTORY };
    try {
      project = await http("POST", q("/v11/projects"), { token, json: repo ? { ...base, gitRepository: { type: "github", repo } } : base });
      ok(`Created project “${name}”${repo ? ` linked to ${repo} (pushes to main auto-deploy)` : ""}`);
    } catch (e) {
      warn(`Couldn't link GitHub (${e.message}). Creating it without Git — deploys go through this script.`);
      try {
        project = await http("POST", q("/v11/projects"), { token, json: base });
        ok(`Created project “${name}”`);
      } catch (e2) {
        return fail(`Vercel: ${e2.message}`);
      }
    }
  }
  state.vercel = { token, team, project };
  await syncVercelEnv(env, state);

  if (!(await confirm("  Deploy to production now?"))) return;
  if (!deploy(state)) return;
  try {
    const { domains = [] } = await http("GET", q(`/v9/projects/${project.id}/domains`), { token });
    const domain = domains.find((d) => !d.name.includes("-git-") && d.name.endsWith(".vercel.app")) || domains[0];
    if (domain) state.siteUrl = `https://${domain.name}`;
  } catch {
    /* fall back to asking */
  }
}

async function syncVercelEnv(env, state) {
  const { token, team, project } = state.vercel;
  const keys = GROUPS.flatMap(([, k]) => k).filter((k) => env[k]);
  const body = keys.map((key) => ({ key, value: env[key], type: "encrypted", target: ["production", "preview", "development"] }));
  try {
    await http("POST", `${VERCEL_API}/v10/projects/${project.id}/env?upsert=true${team ? `&slug=${encodeURIComponent(team)}` : ""}`, { token, json: body });
    ok(`Uploaded ${keys.length} env vars to Vercel`);
  } catch (err) {
    fail(`Vercel env: ${err.message}`);
  }
}

/** Deploys from the repo root; Vercel builds careerprep-ai/ because of the project's Root Directory. */
function deploy(state) {
  const { token, team, project } = state.vercel;
  const args = ["-y", "vercel@latest", "deploy", "--prod", "--yes", `--token=${token}`];
  if (team) args.push(`--scope=${team}`);
  // Env-var linking (instead of writing .vercel/project.json) leaves any existing link in this repo untouched.
  const done = run("npx", args, { cwd: REPO_DIR, env: { ...process.env, VERCEL_ORG_ID: project.accountId, VERCEL_PROJECT_ID: project.id } });
  if (done) ok("Deployed");
  else fail("Deploy failed — see the Vercel output above.");
  return done;
}

async function finishWiring(env, state) {
  step(4, "Production URL → Stripe webhook + Supabase Auth redirects");
  const suggested = state.siteUrl || env.NEXT_PUBLIC_SITE_URL || "";
  const url = ((await ask(`  Production URL ${dim(suggested ? `[${suggested}]` : "[Enter = skip]")}: `)) || suggested).replace(/\/$/, "");
  if (!url) return warn("Skipped — re-run setup after your first deploy to finish this step.");
  if (!/^https:\/\//.test(url)) return warn("Needs to be an https:// URL — skipped.");
  env.NEXT_PUBLIC_SITE_URL = url;

  if (env.STRIPE_SECRET_KEY && (!env.STRIPE_WEBHOOK_SECRET || (await confirm("  Create a new Stripe webhook endpoint anyway?", false)))) {
    try {
      const form = new URLSearchParams({ url: `${url}/api/stripe/webhook`, description: "CareerPrep AI plan sync" });
      WEBHOOK_EVENTS.forEach((e) => form.append("enabled_events[]", e));
      const hook = await http("POST", `${STRIPE_API}/webhook_endpoints`, { token: env.STRIPE_SECRET_KEY, form });
      env.STRIPE_WEBHOOK_SECRET = hook.secret;
      ok(`Stripe webhook → ${url}/api/stripe/webhook`);
    } catch (err) {
      fail(`Stripe webhook: ${err.message}`);
    }
  }

  const ref = env.NEXT_PUBLIC_SUPABASE_URL?.match(/^https:\/\/([a-z0-9-]+)\./)?.[1];
  if (ref && (await confirm("  Point Supabase Auth (magic links, Google) at this URL?"))) {
    console.log(dim("  supabase.com/dashboard/account/tokens → Generate new token (sbp_…). Not saved anywhere."));
    const sbToken = await ask("  Supabase access token: ", { secret: true });
    if (sbToken) {
      try {
        await http("PATCH", `${SUPABASE_API}/projects/${ref}/config/auth`, {
          token: sbToken,
          json: { site_url: url, uri_allow_list: [`${url}/**`, "http://localhost:3000/**"].join(",") },
        });
        ok("Supabase Auth site URL + redirect allow-list updated");
      } catch (err) {
        fail(`Supabase Auth: ${err.message} — set it in Authentication → URL Configuration instead.`);
      }
    }
  }

  writeEnv(env);
  ok("Updated .env.local");
  if (state.vercel) {
    await syncVercelEnv(env, state);
    if (await confirm("  Redeploy so production picks up the new values?")) deploy(state);
  }
}

/* ------------------------------------------------------------------ */

async function main() {
  console.log(bold("\nCareerPrep AI · setup"));
  console.log(dim(`  App folder: ${APP_DIR}`));
  const major = Number(process.versions.node.split(".")[0]);
  if (major < 20) {
    fail(`Node ${process.versions.node} detected — Node 20+ is required.`);
    process.exit(1);
  }
  const env = readEnv();
  const state = {};
  await collectKeys(env);
  await pushSchema();
  await vercelProject(env, state);
  await finishWiring(env, state);

  step(5, "Done");
  const missing = ["NEXT_PUBLIC_SUPABASE_URL", "NEXT_PUBLIC_SUPABASE_ANON_KEY", "SUPABASE_SERVICE_ROLE_KEY", "STRIPE_SECRET_KEY", "STRIPE_PRICE_ID", "STRIPE_WEBHOOK_SECRET"].filter((k) => !env[k]);
  if (missing.length) warn(`Still empty: ${missing.join(", ")} — re-run npm run setup to fill them.`);
  else ok("All required keys are set.");
  console.log(dim("  Local dev: npm run dev → http://localhost:3000"));
  console.log(dim("  Optional: enable Google sign-in in Supabase → Authentication → Providers → Google."));
  rl.close();
}

main().catch((err) => {
  fail(err.stack || err.message);
  rl.close();
  process.exit(1);
});
